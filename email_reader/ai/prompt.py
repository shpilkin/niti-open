def render_projects(projects: list[dict]) -> str:
    """projects: [{name, prompt}] -> a block appended after the rendered thread."""
    lines = ["", "ПРОЕКТЫ:"]
    for p in projects:
        lines.append(f"### {p['name']}")
        lines.append((p.get("prompt") or "").strip() or "(без описания)")
        lines.append("")
    return "\n".join(lines)


# Caps to keep the prompt within the model context window. A few pathological threads
# (huge bodies / thousands of messages from bad threading) otherwise blow past even a 1M
# token limit -> ContextWindowExceededError. Commitments live in the recent/short parts,
# so truncating long bodies is safe. ~1 char ≈ 0.25 token, so 120k chars ≈ 30k tokens.
_MAX_BODY_CHARS = 6_000       # per message
_MAX_THREAD_CHARS = 120_000   # whole rendered thread


def render_thread(messages: list[dict], today: date) -> str:
    """messages: [{is_me, who, sent_at, subject, body}] in chronological order."""
    lines = [f"TODAY: {today.isoformat()}", ""]
    for i, m in enumerate(messages, 1):
        tag = "[Я]" if m["is_me"] else f"[{m['who']}]"
        when = m["sent_at"].date().isoformat() if m.get("sent_at") else "?"
        subj = m.get("subject") or ""
        lines.append(f"--- Сообщение {i} {tag} {when} | Тема: {subj}")
        body = (m.get("body") or "").strip() or "(пусто)"
        if len(body) > _MAX_BODY_CHARS:
            body = body[:_MAX_BODY_CHARS] + "\n…[сообщение обрезано]"
        lines.append(body)
        lines.append("")
    text = "\n".join(lines)
    if len(text) > _MAX_THREAD_CHARS:
        text = text[:_MAX_THREAD_CHARS] + "\n…[тред обрезан]"
    return text


